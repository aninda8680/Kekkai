'use client';

import React from 'react';
import Link from 'next/link';
import { usePathname } from 'next/navigation';

export function SidebarNav() {
  const pathname = usePathname() || '';

  const isProjectsActive =
    pathname === '/dashboard' ||
    pathname.startsWith('/dashboard/projects');

  const isAuditActive = pathname.startsWith('/dashboard/audit');
  const isSettingsActive = pathname.startsWith('/dashboard/settings');

  return (
    <nav className="flex-1 p-3 space-y-1 overflow-y-auto">
      <NavItem
        href="/dashboard"
        icon={<GridIcon />}
        label="Projects"
        active={isProjectsActive}
      />
      <NavItem
        href="/dashboard/audit"
        icon={<AuditIcon />}
        label="Audit Logs"
        active={isAuditActive}
      />
      <NavItem
        href="/dashboard/settings"
        icon={<SettingsIcon />}
        label="Settings"
        active={isSettingsActive}
      />
    </nav>
  );
}

function NavItem({
  href,
  icon,
  label,
  active,
}: {
  href: string;
  icon: React.ReactNode;
  label: string;
  active?: boolean;
}) {
  return (
    <Link
      href={href}
      className={`flex items-center gap-3 px-3 py-2 text-xs font-bold uppercase transition-all font-mono pixel-corners ${
        active
          ? 'bg-brand-soft text-brand-dark border-l-2 border-brand-primary'
          : 'text-text-secondary hover:bg-bg-secondary hover:text-text-primary border-l-2 border-transparent'
      }`}
    >
      <span className={active ? 'text-brand-dark' : 'text-text-secondary'}>{icon}</span>
      {label}
    </Link>
  );
}

